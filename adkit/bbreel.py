#!/usr/bin/env python3
"""Bet builder reel - one fixture, three legs, cut to the beat.

    python3 bbreel.py                          # best upcoming fixture, both brands
    python3 bbreel.py --brand tippsarena --n 3
    python3 bbreel.py --fixture 1517 --vo

WHAT CHANGED FROM THE FIRST VERSION, AND WHY.

His verdict on it was "boring, basic, nothing from this will get over 50 views".
Three things were actually wrong, and only one of them was the design.

1. THE PICK TYPE. The old reel was a correct score. A correct score has exactly
   one thing to reveal, at the end, so there is nothing to build - which is why
   the progress bar felt bolted on. A bet builder has three legs, so the bar IS
   the content: three rungs, three reveals, and the viewer can see how many are
   left. That is the anticipation he asked for, and it comes free with the
   right pick type. The legs come from tippsarena.com's own `ta_markets` meta
   (see bbtips.py) so the video cannot contradict the page it drives traffic to.

2. THE CLOCK. The old reel was cut to the narration - segment lengths were
   whatever the voice took. A video cut to a voice reads as a slideshow with
   commentary. This one is cut to a 150 bpm bed generated by music.py, and at
   150 bpm / 30 fps a beat is EXACTLY 12 frames, so every cut, every caption
   and every rung lands on a beat with no rounding at all. That is most of the
   difference between "fast" and "boring".

3. THE VOICE. He called the German read dead, and measuring it agreed: the
   pitch spread of thorsten-high is 2.9 semitones against 3.7 for the most
   expressive alternative that stays intelligible. But the honest fix is that
   this format does not need a voice - the pick has to be readable in silence
   anyway (his words), and most reels in the reference feed carry music only.
   So narration is now OFF by default and available with --vo.

THE FOOTAGE. `broll/custom/` is checked first and used exclusively if it has
anything in it. Drop his own licensed match clips there and they become the
footage with no code change; nothing else needs touching. The fallback stays
royalty-free (Coverr / Mixkit) rather than broadcast.
"""
